package com.oneui.fontviewer.data.update.model;

/** حالة التحقق من التحديث كما تعرضها صفحة "حول التطبيق". */
public enum UpdateCheckState {
    /** لم يبدأ أي تحقق بعد. */
    IDLE,
    /** التحقق جارٍ الآن (يظهر مؤشر التحميل). */
    CHECKING,
    /** يتوفر إصدار أحدث. */
    UPDATE_AVAILABLE,
    /** النسخة المثبتة هي الأحدث. */
    UP_TO_DATE,
    /** تعذر التحقق بسبب الاتصال نفسه (لا شبكة نشطة، أو انقطاع/مهلة أثناء الطلب). */
    NO_CONNECTION,
    /** الاتصال سليم لكن مصدر التحديث لم يعطِ جواباً صالحاً (رفض الطلب أو رد غير مفهوم). */
    CHECK_FAILED
}
